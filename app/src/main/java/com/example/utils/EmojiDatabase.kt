    private fun generateEmojis(ranges: List<IntRange>): List<String> {
        val list = mutableListOf<String>()
        for (range in ranges) {
            for (code in range) {
                try {
                    if (Character.isValidCodePoint(code)) {
                        list.add(String(Character.toChars(code)))
                    }
                } catch (e: Exception) {
                    // Ignore
                }
            }
        }
        return list.distinct()
    }

    fun findEmojiForText(text: String): String {
        val trimmed = text.trim().lowercase()
        if (trimmed.isEmpty()) return "❓"

        // 1. Check exact key in Korean map
        val directMatch = emojiMap[trimmed]
        if (directMatch != null) return directMatch

        // 2. Check exact key in English map
        val englishMatch = englishEmojiMap[trimmed]
        if (englishMatch != null) return englishMatch

        // 3. Check contains key in Korean Map
        for ((key, emoji) in emojiMap) {
            if (trimmed.contains(key) || key.contains(trimmed)) {
                return emoji
            }
        }

        // 4. Check contains key in English Map
        for ((key, emoji) in englishEmojiMap) {
            if (trimmed.contains(key) || key.contains(trimmed)) {
                return emoji
            }
        }

        // Fallback: Show a friendly sparkles or default emoji instead of nothing
        return "✨"
    }
